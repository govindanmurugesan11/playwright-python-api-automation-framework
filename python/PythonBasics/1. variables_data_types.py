"""
Topic: Variables and Data Types
"""

name = "Govindan"
experience = 15
salary = 75000.50
is_automation_engineer = True

print(name)                         # Govindan
print(type(name))                   # <class 'str'>

print(experience)                   # 15
print(type(experience))             # <class 'int'>

print(salary)                       # 75000.5
print(type(salary))                 # <class 'float'>

print(is_automation_engineer)       # True
print(type(is_automation_engineer)) # <class 'bool'>